let currentLang = LANG_DEFAULT;

function getLang() {
  try { const v = localStorage.getItem("ckwb.lang"); if (v && LANGS.includes(v)) return v; } catch { }
  return LANG_DEFAULT;
}

function setLang(lang) {
  if (!LANGS.includes(lang)) lang = LANG_DEFAULT;
  currentLang = lang;
  try { localStorage.setItem("ckwb.lang", lang); } catch { }
  document.documentElement.lang = lang;
  updateDOM();
}

function t(key, ...params) {
  const dict = T[currentLang] || T[LANG_DEFAULT];
  let text = dict[key] || T[LANG_DEFAULT][key] || key;
  if (params.length) {
    text = text.replace(/{(\d+)}/g, (m, i) => params[i] !== undefined ? params[i] : m);
    text = text.replace(/\{(\w+)\}/g, (m, name) => params[name] !== undefined ? params[name] : m);
  }
  return text;
}

function updateDOM() {
  const $$ = (s, el = document) => [...el.querySelectorAll(s)];
  $$("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (!key) return;
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      if (el.dataset.i18nPlaceholder) el.placeholder = t(el.dataset.i18nPlaceholder);
      return;
    }
    // Defensive guard: if the element contains child elements, the markup must wrap
    // the translatable text in its own span (data-i18n on the span); do not destroy
    // the children by overwriting textContent here.
    if (el.children && el.children.length) return;
    el.textContent = t(key);
  });
  $$("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  $$("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
  $$("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  $$("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.documentElement.lang = currentLang;
}

(function () {
  setLang(getLang());
})();

window.i18n = { t: t, setLang: setLang, getLang: getLang, updateDOM: updateDOM, T: T, LANGS: LANGS };
